import type { CSSProperties, ReactNode } from "react";
import map from "@/content/geo/map.json";
import { Mark } from "@/components/marks/Mark";
import { MapStage } from "./MapStage";

/**
 * The map as an architect's model: a white sheet with the graticule, the neighbouring countries
 * barely raised, Italy as a pale block, and the regions where the group works raised higher in
 * the brand navy — the way a model shows its subject in colour on a white context. Every place
 * stands as a model pin: a dot on the ground with a ring that pulses, a thin rod, a flag with
 * the town's name.
 *
 * Cartography: Natural Earth 1:10m (public domain), generated by tools/build-map.mjs into one
 * static file, public/map/italia.svg, that every layer references with <use>: the browser
 * downloads it once and caches it, and the page HTML stays light.
 */
const SRC = "/map/italia.svg";
const V = map.view; // km, y south
const LAT0 = (42 * Math.PI) / 180;
const R = 6371;
const project = (lat: number, lon: number) => [R * (((lon - 12.5) * Math.PI) / 180) * Math.cos(LAT0), -R * (((lat - 42) * Math.PI) / 180)];
type View = { x: number; y: number; w: number; h: number };

/** A view `scale` times closer, centred on a point and kept inside the sheet. */
export const viewAround = (x: number, y: number, scale: number): View => {
  const w = V.w / scale, h = V.h / scale;
  return { x: Math.min(Math.max(x - w / 2, V.x), V.x + V.w - w), y: Math.min(Math.max(y - h / 2, V.y), V.y + V.h - h), w, h };
};
const vb = (v: View) => `${v.x.toFixed(1)} ${v.y.toFixed(1)} ${v.w.toFixed(1)} ${v.h.toFixed(1)}`;

// graticule every two degrees, as printed on the sheet
const LONS = [8, 10, 12, 14, 16, 18];
const LATS = [38, 40, 42, 44, 46];

// heights of the model, px: Italy's block, then the raised regions on top of it
const IT_SIDES = [2, 4, 6];
const IT_TOP = 8;
const OP_SIDES = [10, 12, 14];
const OP_TOP = 16;

export type MapPin = {
  key: string;
  lat: number;
  lon: number;
  kind: "office" | "project";
  /** the town, on the flag */
  label: string;
  /** a word after the town on the flag: an operation's year */
  note?: string;
  /** the region it raises, as named in content/geo/map.json `regions` */
  area: string;
};
export type MapPlace = MapPin & {
  /** the list entry: usually a link to the case, plain text for an office */
  item: ReactNode;
};

/** A place in sheet units (km, y south). */
export const placeXY = (p: { lat: number; lon: number }) => project(p.lat, p.lon);

const Layer = ({ ids, z, className, view }: { ids: string[]; z: number; className: string; view: string }) => (
  <svg className={`vp-map__layer vp-map__cut ${className}`} viewBox={view} aria-hidden="true" focusable="false" style={{ "--z": `${z}px` } as CSSProperties}>
    {ids.map((id) => (
      <use key={id} href={`${SRC}#${id}`} />
    ))}
  </svg>
);

type Cluster = { keys: string[]; kind: MapPin["kind"]; label: string; note?: string; xy: [number, number] };

/** Places a few km apart (an office and an operation in the same town) share one pin. */
function clusters(pins: MapPin[], focus?: string): Cluster[] {
  const out: (Cluster & { members: MapPin[] })[] = [];
  for (const p of pins) {
    const xy = placeXY(p) as [number, number];
    const c = out.find((c) => Math.hypot(c.xy[0] - xy[0], c.xy[1] - xy[1]) < 8);
    if (c) c.members.push(p);
    else out.push({ keys: [], kind: p.kind, label: p.label, xy, members: [p] });
  }
  return out.map(({ members, xy }) => {
    // the flag speaks for the focused place, else for an office, else for the first
    const lead = members.find((m) => m.key === focus) ?? members.find((m) => m.kind === "office") ?? members[0];
    return { keys: members.map((m) => m.key), kind: lead.kind, label: lead.label, note: lead.note, xy };
  });
}

type Flag = { stem: number; west: boolean };
type Metrics = { char: number; pad: number; h: number; stems: number[] };
const WIDE: Metrics = { char: 7.2, pad: 34, h: 24, stems: [22, 48, 74, 100] };
const NARROW: Metrics = { char: 5.7, pad: 26, h: 19, stems: [14, 32, 50, 68] };
const NARROW_W = 340;

/**
 * Rod heights and sides so that no two flags overlap, laid out for a model `width` px wide:
 * the pins nearest the viewer take the short rods, those behind rise above them, and a flag
 * opens to the west when the east is taken or would leave the model.
 */
function flags(cs: Cluster[], view: View, width: number, m: Metrics): Flag[] {
  const k = (width * 0.92) / view.w; // px per km across the plane
  const ky = k * 0.72; // the tilt shortens depth
  const top = -0.04 * width; // the headroom above the sheet, inside the stage
  type Box = { x0: number; x1: number; y0: number; y1: number };
  const placed: Box[] = [];
  const free = (b: Box) => !placed.some((p) => b.x0 < p.x1 && b.x1 > p.x0 && b.y0 < p.y1 && b.y1 > p.y0);
  const out = new Array<Flag>(cs.length);
  cs.map((c, i) => ({ c, i, x: (c.xy[0] - view.x) * k + width * 0.04, y: (c.xy[1] - view.y) * ky }))
    .sort((a, b) => b.y - a.y)
    .forEach(({ c, i, x, y }) => {
      const w = m.pad + (c.label.length + (c.note ? c.note.length + 1.5 : 0)) * m.char;
      const box = (stem: number, west: boolean): Box => ({ x0: west ? x - w - 3 : x - 3, x1: west ? x + 3 : x + w + 3, y0: y - stem - m.h, y1: y - stem + 2 });
      const inside = (b: Box) => b.x0 >= 0 && b.x1 <= width && b.y0 >= top;
      const options = m.stems.flatMap((stem) => [false, true].map((west) => ({ stem, west, b: box(stem, west) })));
      const pick = options.find((o) => free(o.b) && inside(o.b)) ?? options.find((o) => free(o.b)) ?? options[options.length - 1];
      placed.push(pick.b);
      out[i] = { stem: pick.stem, west: pick.west };
    });
  return out;
}

/**
 * The tilted model. `focus` lights one place, dims the others and keeps only its flag;
 * `zoom` frames the sheet that many times closer around it, `frame` around any point
 * (both computed here, so they need no JavaScript). Zooming moves the SVG viewBox, never
 * a CSS scale, so the cartography is redrawn sharp. `width` is the model's usual width on
 * screen, px, for laying out the flags (phones get their own, narrower layout).
 */
export function MapSlab({
  places,
  focus,
  zoom,
  frame,
  zoomTargets,
  zoomScale = 2.6,
  width = 600,
  className = "",
}: {
  places: MapPin[];
  focus?: string;
  zoom?: number;
  /** a resting view closer than the whole sheet, centred on a point, with no place lit */
  frame?: { lat: number; lon: number; scale: number };
  zoomTargets?: boolean;
  /** how close the hover zoom gets */
  zoomScale?: number;
  width?: number;
  className?: string;
}) {
  const focused = places.find((p) => p.key === focus);
  const view: View =
    focused && zoom ? viewAround(...(placeXY(focused) as [number, number]), zoom) : frame ? viewAround(...(placeXY(frame) as [number, number]), frame.scale) : V;
  const viewBox = vb(view);
  const cs = clusters(places, focus);
  const flagged = cs.map((c) => !focus || c.keys.includes(focus));
  const shown = cs.filter((_, i) => flagged[i]);
  const wide = flags(shown, view, width, WIDE);
  const narrow = flags(shown, view, Math.min(width, NARROW_W), NARROW);
  const areas = [...new Set(places.map((p) => p.area))].filter((a) => map.regions.includes(a));
  // a pin names its town: the printed city beside it gives way
  const named = (x: number, y: number) => cs.some((c) => Math.hypot(c.xy[0] - x, c.xy[1] - y) < 15);
  // a pin just east of a city would stand on its name: the name moves to the west of the dot
  const eastOf = (x: number, y: number) => cs.some((c) => c.xy[0] - x > 15 && c.xy[0] - x < 80 && Math.abs(c.xy[1] - y) < 35);
  const cities = (high: boolean) =>
    Object.entries(map.cities)
      .filter(([, [x, y, r]]) => areas.includes(r as string) === high && !named(x as number, y as number))
      .map(([name, [x, y]]) => {
        const west = eastOf(x as number, y as number);
        return (
          <g key={name}>
            <circle cx={x} cy={y} r={4.5} />
            <text x={x} y={y} textAnchor={west ? "end" : undefined} style={{ "--off": west ? -11 : 11 } as CSSProperties}>
              {name}
            </text>
          </g>
        );
      });
  let flagIndex = 0;

  return (
    <MapStage
      className={className}
      focused={!!focus}
      sheet={V}
      view={view}
      targets={zoomTargets ? Object.fromEntries(places.map((p) => [p.key, viewAround(...(placeXY(p) as [number, number]), zoomScale)])) : undefined}
    >
      {/* the sheet: thickness below, then the printed face */}
      <span className="vp-map__edge" style={{ "--z": "-6px" } as CSSProperties} aria-hidden="true" />
      <span className="vp-map__edge" style={{ "--z": "-3px" } as CSSProperties} aria-hidden="true" />
      <svg className="vp-map__layer vp-map__cut vp-map__sheet" viewBox={viewBox} aria-hidden="true" focusable="false" style={{ "--z": "0px" } as CSSProperties}>
        <rect x={V.x} y={V.y} width={V.w} height={V.h} />
        <g className="vp-map__grat">
          {LONS.map((lon) => {
            const [x] = project(42, lon);
            return <line key={`x${lon}`} x1={x} x2={x} y1={V.y} y2={V.y + V.h} />;
          })}
          {LATS.map((lat) => {
            const [, y] = project(lat, 12.5);
            return <line key={`y${lat}`} x1={V.x} x2={V.x + V.w} y1={y} y2={y} />;
          })}
        </g>
        <g className="vp-map__gratlabel">
          {LONS.map((lon) => {
            const [x] = project(42, lon);
            return (
              <text key={`tx${lon}`} x={x + 6} y={V.y + V.h - 14}>
                {lon}°E
              </text>
            );
          })}
          {LATS.map((lat) => {
            const [, y] = project(lat, 12.5);
            return (
              <text key={`ty${lat}`} x={V.x + 12} y={y - 6}>
                {lat}°N
              </text>
            );
          })}
        </g>
      </svg>
      {/* neighbouring countries, barely raised; Italy, a pale block */}
      <Layer ids={["neighbours"]} z={1.5} className="vp-map__nb vp-map__nb--side" view={viewBox} />
      <Layer ids={["neighbours"]} z={3} className="vp-map__nb" view={viewBox} />
      {IT_SIDES.map((z) => (
        <Layer key={z} ids={["italy"]} z={z} className="vp-map__it vp-map__it--side" view={viewBox} />
      ))}
      <Layer ids={["italy"]} z={IT_TOP} className="vp-map__it" view={viewBox} />
      <svg className="vp-map__layer vp-map__cut vp-map__deco" viewBox={viewBox} aria-hidden="true" focusable="false" style={{ "--z": `${IT_TOP + 0.2}px` } as CSSProperties}>
        <use href={`${SRC}#lakes`} className="vp-map__lakes" />
        <use href={`${SRC}#regions`} className="vp-map__regions" />
        <g className="vp-map__cities">{cities(false)}</g>
      </svg>
      {/* the regions where the group works, raised in navy, with their own lakes and cities */}
      {OP_SIDES.map((z) => (
        <Layer key={z} ids={areas.map((a) => `r-${a}`)} z={z} className="vp-map__op vp-map__op--side" view={viewBox} />
      ))}
      <Layer ids={areas.map((a) => `r-${a}`)} z={OP_TOP} className="vp-map__op" view={viewBox} />
      <svg className="vp-map__layer vp-map__cut vp-map__deco" viewBox={viewBox} aria-hidden="true" focusable="false" style={{ "--z": `${OP_TOP + 0.2}px` } as CSSProperties}>
        {areas.map((a) => (
          <use key={a} href={`${SRC}#lakes-${a}`} className="vp-map__lakes" />
        ))}
        <g className="vp-map__cities vp-map__cities--high">{cities(true)}</g>
      </svg>
      {cs.map((c, i) => {
        const left = ((c.xy[0] - view.x) / view.w) * 100;
        const top = ((c.xy[1] - view.y) / view.h) * 100;
        const on = focus && c.keys.includes(focus);
        const f = flagged[i] ? flagIndex++ : -1;
        return (
          <span
            key={c.keys.join(" ")}
            className="vp-map__pin"
            data-k={c.keys.join(" ")}
            data-kind={c.kind}
            data-west={f >= 0 && wide[f].west ? "" : undefined}
            data-west-n={f >= 0 && narrow[f].west ? "" : undefined}
            data-x={c.xy[0].toFixed(1)}
            data-y={c.xy[1].toFixed(1)}
            style={{ left: `${left}%`, top: `${top}%`, "--i": i, ...(on ? { "--on": 1 } : null) } as CSSProperties}
            aria-hidden="true"
          >
            <span className="vp-map__ring" />
            <span className="vp-map__dot" />
            {flagged[i] ? (
              <span className="vp-map__flag" style={{ "--stem": `${wide[f].stem}px`, "--stem-n": `${narrow[f].stem}px` } as CSSProperties}>
                <span className="vp-map__tag">
                  <Mark kind={c.kind === "office" ? "solid" : "outline"} />
                  {c.label}
                  {c.note ? <span className="vp-map__note t-num">{c.note}</span> : null}
                </span>
              </span>
            ) : null}
          </span>
        );
      })}
    </MapStage>
  );
}

/** CSS that lights a place's pin while its entry (`.vp-map__item` or `[data-map-target]`) is hovered or focused. */
export const lightRules = (keys: string[]) =>
  keys
    .map((k) => `.vp-map:has(:is(.vp-map__item,[data-map-target])[data-k="${k}"]:is(:hover,:focus-within)) .vp-map__pin[data-k~="${k}"]{--on:1}`)
    .join("");

/**
 * The model with the list beside it: the list is the readable, accessible version.
 * Hovering or focusing an entry lights its pin and dims the others (CSS, one rule per
 * place, above) and, on wide screens, zooms the cartography onto it (MapStage).
 */
export function ItalyMap({ places, caption, label }: { places: MapPlace[]; caption: string; label: string }) {
  return (
    <figure className="vp-map grid-12 gap-y-10" aria-label={label}>
      <style>{lightRules(places.map((p) => p.key))}</style>
      <div className="col-span-4 lg:col-span-7">
        <MapSlab places={places} zoomTargets width={680} />
      </div>
      <div className="col-span-4 lg:col-span-4 lg:col-start-9 lg:self-center">
        <ol className="vp-map__list">
          {places.map((p) => (
            <li key={p.key} className="vp-map__item" data-k={p.key} data-kind={p.kind}>
              {p.item}
            </li>
          ))}
        </ol>
        <figcaption className="t-label mt-6">{caption}</figcaption>
      </div>
    </figure>
  );
}
